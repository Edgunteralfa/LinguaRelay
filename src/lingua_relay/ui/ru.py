_LONG = tuple(sorted((key for key in TEXT if len(key) >= 2), key=len, reverse=True))


def ru(text: str) -> str:
    """Translate interface copy. Unknown text is returned unchanged."""
    if not isinstance(text, str) or not text or _CJK.search(text) is None:
        return text
    exact = TEXT.get(text)
    if exact is not None:
        return exact
    out = text
    for key in _LONG:
        if key in out:
            out = out.replace(key, TEXT[key])
    return out
